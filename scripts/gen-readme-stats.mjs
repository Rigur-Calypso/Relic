// Regenerate the README's "Real results" block from the live data in data/.
// Keeps the headline numbers and the knowledge-loss table honest and drift-free.
// Fills the region between <!-- AUTOSTATS:START --> and <!-- AUTOSTATS:END -->.
import { readFile, writeFile, readdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const README = resolve(ROOT, 'README.md');

const targets = JSON.parse(await readFile(resolve(ROOT, 'targets.json'), 'utf8'));
const nameOf = Object.fromEntries(targets.map(t => [t.id, t.name]));

const files = (await readdir(resolve(ROOT, 'data', 'analysis'))).filter(f => f.endsWith('.json'));
let instruments = 0, loss = 0, intact = 0, none = 0, withHistory = 0;
const lossRows = [];
for (const f of files) {
  const id = f.replace('.json', '');
  if (id === 'decoy') continue;
  const a = JSON.parse(await readFile(resolve(ROOT, 'data', 'analysis', f), 'utf8'));
  let count = 0;
  try { count = (JSON.parse(await readFile(resolve(ROOT, 'data', 'current', f), 'utf8')).equipment || []).length; } catch { /* no current */ }
  instruments += count;
  if (a.vitalityScore == null) { none++; }
  else { withHistory++; if (a.knowledgeLoss) loss++; else intact++; }
  if (a.knowledgeLoss && a.vitalityScore != null) {
    const removedNames = (a.removed || []).map(r => r.name).filter(Boolean);
    lossRows.push({ id, name: nameOf[id] || id, v: a.vitalityScore, removed: removedNames });
  }
}
const total = targets.filter(t => t.id !== 'decoy').length;

lossRows.sort((x, y) => x.v - y.v);
const top = lossRows.slice(0, 10);
const tableRows = top.map(r => {
  const detail = r.removed.length
    ? (r.removed.slice(0, 3).join(', ') + (r.removed.length > 3 ? `, +${r.removed.length - 3} more` : ''))
    : `${r.removed.length} removed`;
  return `| **${r.name}** | **${Math.round(r.v)}** ⚠ | ${detail} |`;
}).join('\n');

const block = `<!-- AUTOSTATS:START -->
<!-- Generated by scripts/gen-readme-stats.mjs — do not edit by hand. -->

**${total} facilities monitored across the US, India, Europe, and Asia-Pacific — ${instruments.toLocaleString()} instruments tracked.**
National labs and university core/nanofab facilities across five continents. Every card is
generated by the live pipeline — **${withHistory} facilities have a real historical diff, and
${loss} show genuine, specific knowledge loss:**

| Facility | Vitality | Knowledge loss detected |
|----------|:--------:|-------------------------|
${tableRows}

> No ordinary scraper — however healthy — would have caught any of these.
> ${none} facilities show "no history" (no usable Wayback capture — rich current data only);
> ${intact} show fully preserved knowledge.
<!-- AUTOSTATS:END -->`;

let md = await readFile(README, 'utf8');
const re = /<!-- AUTOSTATS:START -->[\s\S]*?<!-- AUTOSTATS:END -->/;
if (re.test(md)) {
  md = md.replace(re, block);
} else {
  // First run: replace the legacy hand-written "Real results" body between the
  // "## Real results" heading and the next "---" divider.
  md = md.replace(/(## Real results[^\n]*\n)([\s\S]*?)(\n---)/, `$1\n${block}\n$3`);
}
await writeFile(README, md);
console.log(`[readme] updated stats: ${total} facilities, ${instruments} instruments, ${loss} loss, ${intact} intact, ${none} no-history. Top loss: ${top.map(t => t.id).slice(0, 5).join(', ')}`);
